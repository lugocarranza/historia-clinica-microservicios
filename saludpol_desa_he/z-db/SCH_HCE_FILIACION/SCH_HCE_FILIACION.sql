    V_CREATED_BY VARCHAR2(50 BYTE),
    T_UPDATED_AT DATE,
    V_UPDATED_BY VARCHAR2(50 BYTE)
);
COMMENT ON COLUMN SCH_HCE_FILIACION.TBL_HISTORIA_CLINICA.V_NRO_HC IS 'Número legible de la HC. Ej: HC-0045231.';

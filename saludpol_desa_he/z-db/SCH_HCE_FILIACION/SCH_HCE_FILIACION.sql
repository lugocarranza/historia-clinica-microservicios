-- Triggers de secuencias
CREATE OR REPLACE TRIGGER SCH_HCE_FILIACION.TRG_TBL_ADMISION_BI
    BEFORE INSERT ON SCH_HCE_FILIACION.TBL_ADMISION
    FOR EACH ROW
BEGIN
    IF :NEW.I_ID IS NULL THEN
    :NEW.I_ID := SEQ_ADMISION.NEXTVAL;
    END IF;
END;

/

CREATE OR REPLACE TRIGGER SCH_HCE_FILIACION.TRG_TBL_HC_BI
    BEFORE INSERT ON SCH_HCE_FILIACION.TBL_HISTORIA_CLINICA
    FOR EACH ROW
BEGIN
    IF :NEW.I_ID IS NULL THEN
    :NEW.I_ID := SEQ_HISTORIA_CLINICA.NEXTVAL;
    END IF;
END;

/

